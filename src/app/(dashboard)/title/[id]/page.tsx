import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ArrowLeft, ExternalLink } from "lucide-react";
import { Button } from "@/components/ui/button";
import { TitleActions } from "@/components/releases/TitleActions";
import { PlatformBadge, VerdictBadge } from "@/components/releases/badges";
import { Poster } from "@/components/releases/Poster";
import { PROVIDERS } from "@/config/providers";
import { languageLabel } from "@/config/taxonomy";
import { requirePageUser } from "@/lib/auth/session";
import { formatDay, formatTimestamp } from "@/lib/dates/ist";
import { getPreferences } from "@/lib/db/users";
import { DATE_TYPE_LABEL } from "@/lib/release/eligibility";
import { safeLink } from "@/lib/telegram/format";
import { getTitleDetail } from "@/services/catalogue.service";

export const metadata: Metadata = { title: "Title" };

export default async function TitlePage({ params, searchParams }: PageProps<"/title/[id]">) {
  const { id } = await params;
  const sp = await searchParams;
  if (!/^[0-9a-f-]{36}$/i.test(id)) notFound();
  const { user, db } = await requirePageUser();
  const prefs = await getPreferences(db, user.id);
  const detail = await getTitleDetail(db, user.id, id, prefs);
  if (!detail) notFound();
  const { title: t, item } = detail;
  const back = typeof sp.back === "string" && sp.back.startsWith("/") && !sp.back.startsWith("//") ? sp.back : "/this-week";
  const rec = item?.recommendation ?? null;
  const releases = item?.releases ?? [];

  const facts: [string, string][] = [
    ["Type", t.mediaType === "movie" ? "Movie" : "TV series"],
    ["Original language", languageLabel(t.originalLanguage)],
    ...(t.originalTitle ? [["Original title", t.originalTitle] as [string, string]] : []),
    ["Runtime", t.mediaType === "movie" ? (t.runtimeMinutes ? `${t.runtimeMinutes} minutes` : "Not available") : t.episodeRuntimeMinutes ? `~${t.episodeRuntimeMinutes} min per episode` : "Not available"],
    ...(t.mediaType === "tv" ? [["Seasons / episodes", `${t.numberOfSeasons ?? "—"} seasons · ${t.numberOfEpisodes ?? "—"} episodes in total`] as [string, string]] : []),
    ["Metadata source", "TMDB"],
    ["Metadata updated", formatTimestamp(t.metadataUpdatedAt) + " IST"],
  ];

  return (
    <article className="space-y-10">
      <Button asChild variant="ghost" size="sm"><Link href={back}><ArrowLeft /> Back</Link></Button>
      <section className="relative isolate overflow-hidden rounded-3xl border border-border">
        <div className="absolute inset-0 -z-10">
          <Poster path={t.backdropPath} alt="" size="w1280" sizes="100vw" priority className="opacity-50" />
          <div className="absolute inset-0 scrim-l" />
          <div className="absolute inset-0 scrim-b" />
        </div>
        <div className="grid gap-8 p-6 sm:p-10 md:grid-cols-[220px_1fr]">
          <div className="relative mx-auto aspect-[2/3] w-44 overflow-hidden rounded-2xl border border-white/10 bg-muted shadow-2xl md:w-full">
            <Poster path={t.posterPath} alt={`${t.title} poster`} sizes="220px" fallbackLabel={t.title} />
          </div>
          <div className="flex flex-col justify-end gap-4">
            <div className="flex flex-wrap gap-2">{item?.platforms.map((p) => <PlatformBadge key={p} platform={p} />)}</div>
            <h1 className="font-display text-5xl leading-none sm:text-6xl">{t.title}</h1>
            <div className="flex flex-wrap gap-1.5">
              {t.genreNames.map((g) => <span key={g} className="rounded-md bg-white/10 px-2 py-0.5 text-xs">{g}</span>)}
            </div>
            <p className="max-w-2xl leading-relaxed text-foreground/80">{t.overview ?? "TMDB has no synopsis for this title yet."}</p>
            {item && <TitleActions item={item} prefs={prefs} />}
          </div>
        </div>
      </section>

      <div className="grid gap-6 lg:grid-cols-[1.2fr_1fr]">
        <section className="rounded-2xl border border-border bg-card p-6">
          <h2 className="font-display text-2xl">AI recommendation</h2>
          {rec ? (
            <div className="mt-4 space-y-3">
              <div className="flex items-center gap-3">
                <VerdictBadge verdict={rec.verdict} />
                <span className="text-sm">{rec.matchScore}/100 match · {rec.confidence} confidence</span>
              </div>
              <p className="text-foreground/85">{rec.explanation}</p>
              <p className="text-sm italic text-muted-foreground">{rec.synopsis}</p>
              {rec.matchedPreferences.length > 0 && (
                <div className="flex flex-wrap gap-1.5">{rec.matchedPreferences.map((m) => <span key={m} className="rounded bg-cyan/10 px-2 py-0.5 text-xs text-cyan">{m}</span>)}</div>
              )}
              <p className="text-xs text-muted-foreground">Generated by {rec.modelName} · {formatTimestamp(rec.generatedAt)} IST</p>
            </div>
          ) : (
            <p className="mt-3 text-sm text-muted-foreground">No AI recommendation for your current preferences yet. Use “Get AI verdicts” on Discover or This Week.</p>
          )}
        </section>

        <section className="rounded-2xl border border-border bg-card p-6">
          <h2 className="font-display text-2xl">Details</h2>
          <dl className="mt-4 space-y-2 text-sm">
            {facts.map(([k, v]) => (
              <div key={k} className="flex justify-between gap-4 border-b border-border/60 pb-2">
                <dt className="text-muted-foreground">{k}</dt>
                <dd className="text-right">{v}</dd>
              </div>
            ))}
          </dl>
        </section>
      </div>

      <section className="rounded-2xl border border-border bg-card p-6">
        <h2 className="font-display text-2xl">Streaming in India</h2>
        {releases.length === 0 ? (
          <p className="mt-3 text-sm text-muted-foreground">No provider information recorded for this title.</p>
        ) : (
          <ul className="mt-4 divide-y divide-border">
            {releases.map((r) => {
              const link = safeLink(r.sourceUrl);
              return (
                <li key={r.id} className="flex flex-wrap items-center gap-x-4 gap-y-1 py-3 text-sm">
                  <span className="w-28 font-medium">{PROVIDERS[r.providerKey].shortLabel}</span>
                  <span className={r.availabilityStatus === "verified" ? "text-cyan" : "text-maybe"}>{r.availabilityStatus === "verified" ? "Verified" : "Release date unverified"}</span>
                  <span>{r.streamingReleaseDate ? formatDay(r.streamingReleaseDate, true) : "Date not available"} · {DATE_TYPE_LABEL[r.releaseDateType]}{r.seasonNumber ? ` (S${r.seasonNumber}${r.episodeCount ? `, ${r.episodeCount} eps` : ""})` : ""}</span>
                  <span className="text-xs text-muted-foreground">Last verified {formatTimestamp(r.lastVerifiedAt)} IST</span>
                  {link && (
                    <a href={link} target="_blank" rel="noreferrer" className="ml-auto inline-flex items-center gap-1 text-cyan hover:underline">
                      Where to watch (TMDB) <ExternalLink className="size-3.5" />
                    </a>
                  )}
                </li>
              );
            })}
          </ul>
        )}
        <p className="mt-4 text-xs text-muted-foreground">Provider availability comes from TMDB (powered by JustWatch). We don’t link to streaming apps directly because no verified deep link is available.</p>
      </section>
    </article>
  );
}
